const LANGS = ['en', 'hu'];
export const LANG = 'tilth.lang';

// The first device language we support wins: ['de', 'hu'] gives Hungarian, ['de', 'en', 'hu'] English.
export const detect = (langs) => langs.map((l) => l.slice(0, 2).toLowerCase()).find((l) => LANGS.includes(l)) ?? 'en';

let saved = null;
try { saved = localStorage.getItem(LANG); } catch { /* private mode, or Node in tests */ }
export const lang = LANGS.includes(saved) ? saved : detect(globalThis.navigator?.languages ?? []);

export const tr = (en, vars = {}) => ((lang === 'hu' && HU[en]) || en).replace(/\{(\w+)\}/g, (_, k) => vars[k]);
